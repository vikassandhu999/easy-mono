defmodule Mix.Tasks.TypedRoutes.Gen do
  use Mix.Task

  alias EasyWeb.TypedRoute.{Emit, Generator, SchemaMerge, Type}

  @shortdoc "Generate TypeScript from typed routes"

  @apps [
    %{
      name: :client,
      file: "apps/clientapp/src/api/schema.ts",
      prefixes: ["/v1/client", "/v1/auth", "/v1/public", "/api"]
    },
    %{
      name: :coach,
      file: "apps/coachapp/src/api/schema.ts",
      prefixes: ["/v1/coach", "/v1/businesses", "/v1/auth", "/v1/public", "/api"]
    }
  ]

  @impl Mix.Task
  @spec run([String.t()]) :: :ok
  def run(args) do
    Mix.Task.run("compile")
    Application.load(:easy)
    routes = typed_router_entries()
    assert_unique_segments!()

    if "--stdout" in args do
      Mix.shell().info(render_standalone(routes))
    else
      write_or_check(routes, "--check" in args)
    end

    :ok
  end

  defp write_or_check(routes, check?) do
    Enum.each(@apps, &sync_app(&1, routes, check?))
    Mix.shell().info("typed_routes.gen #{if check?, do: "--check ok ", else: ""}(#{length(routes)} typed routes)")
  end

  defp sync_app(app, routes, check?) do
    entries = Enum.filter(routes, fn {route, _, _} -> prefix?(route, app.prefixes) end)
    path = schema_path(app.file)
    source = File.read!(path)
    {types, paths} = fragments(entries)

    if check? do
      check_schema!(source, types, paths, app.file)
    else
      next = SchemaMerge.inject(source, types, paths)
      File.write!(path, next)
    end
  end

  defp check_schema!(source, types, paths, file) do
    unless SchemaMerge.current?(source, types, paths) do
      Mix.raise("typed_routes.gen --check failed for #{file}")
    end
  end

  defp schema_path(rel) do
    Path.expand(Path.join(["..", "frontend", rel]), File.cwd!())
  end

  defp prefix?(route, prefixes) do
    path = Emit.path_template(route.path)
    Enum.any?(prefixes, &(path == &1 or String.starts_with?(path, &1 <> "/")))
  end

  defp typed_router_entries do
    EasyWeb.Router.__routes__()
    |> Enum.filter(&typed_plug?/1)
    |> Enum.map(fn route ->
      route = with_pipeline(route)
      typed = route.plug.__typed_route__(route.plug_opts)
      headers = route.plug.__typed_route_adapter__().headers(route, typed)
      Generator.validate!(route, typed)
      {route, typed, headers}
    end)
  end

  defp with_pipeline(route) do
    path = Regex.replace(~r/:([A-Za-z0-9_]+)/, route.path, "typed-route")
    method = route.verb |> to_string() |> String.upcase()
    %{pipe_through: pipeline} = Phoenix.Router.route_info(EasyWeb.Router, method, path, "localhost")
    Map.put(route, :pipe_through, pipeline)
  end

  defp typed_plug?(route) do
    Code.ensure_loaded?(route.plug) and
      function_exported?(route.plug, :__typed_route__, 1) and
      function_exported?(route.plug, :__typed_route_adapter__, 0) and
      is_map(route.plug.__typed_route__(route.plug_opts))
  end

  defp assert_unique_segments! do
    dupes =
      type_modules()
      |> Enum.group_by(&Type.last_segment/1)
      |> Enum.filter(fn {_seg, mods} -> length(mods) > 1 end)

    if dupes != [] do
      Mix.raise("EasyWeb.Types last segments must be unique: #{inspect(dupes)}")
    end
  end

  defp type_modules do
    {:ok, modules} = :application.get_key(:easy, :modules)

    Enum.filter(modules, fn mod ->
      match?(["EasyWeb", "Types" | _], Module.split(mod)) and
        function_exported?(mod, :__wire_type__, 1)
    end)
  end

  defp render_standalone(entries) do
    {types, paths} = fragments(entries)

    """
    /** Generated by mix typed_routes.gen. Do not edit. */

    #{types}

    export interface paths {
    #{indent(paths, 2)}
    }
    """
  end

  defp fragments(entries) do
    named =
      Enum.reduce(entries, %{}, fn {_route, typed, _headers}, acc ->
        acc
        |> merge_named(typed.body)
        |> merge_named(typed.query)
        |> merge_named(typed.path)
        |> merge_named(elem(typed.ok, 1))
      end)

    {Emit.export_named_types(named), grouped_paths_ts(entries, named)}
  end

  defp merge_named(acc, nil), do: acc
  defp merge_named(acc, ir), do: Emit.named_aliases(ir, acc)

  defp grouped_paths_ts(entries, named) do
    entries
    |> Enum.group_by(fn {route, _, _} -> Emit.path_template(route.path) end)
    |> Enum.sort_by(fn {path, _} -> path end)
    |> Enum.map_join(",\n", &path_object(&1, named))
  end

  defp path_object({path, group}, named) do
    methods =
      group
      |> Enum.sort_by(fn {route, _, _} -> method_name(route.verb) end)
      |> Enum.map_join(",\n", fn entry -> indent(method_entry(entry, named), 2) end)

    "'#{path}': {\n#{methods}\n}"
  end

  defp method_entry({route, typed, headers}, named) do
    method = method_name(route.verb)
    {status, ok_ir} = typed.ok
    statuses = [status | List.wrap(Map.get(typed, :replay_status))]
    responses = Enum.map_join(statuses, "\n", &"#{&1}: #{response_ts(&1, ok_ir, named)};")

    """
    #{method}: {
      parameters: {
        #{query_line(typed.query, named)}
        #{header_line(headers)}
        #{path_line(route.path, typed.path, named)}
        cookie?: never;
      };
      #{body_ts(typed.body, named)}responses: {
        #{responses}
      };
    }
    """
    |> String.trim()
  end

  defp method_name(verb), do: verb |> to_string() |> String.downcase()

  defp header_line([]), do: "header?: never;"

  defp header_line(headers) do
    fields = Enum.map_join(headers, "; ", &header_field/1)
    optional = if Enum.any?(headers, & &1.required?), do: "", else: "?"
    "header#{optional}: { #{fields} };"
  end

  defp header_field(%{name: name, required?: required?}) do
    optional = if required?, do: "", else: "?"
    "#{header_name(name)}#{optional}: string"
  end

  defp header_name(name) do
    if Regex.match?(~r/^[A-Za-z_$][A-Za-z0-9_$]*$/, name), do: name, else: "'#{name}'"
  end

  defp query_line(nil, _named), do: "query?: never;"

  defp query_line(ir, named) do
    ts = Emit.ir_to_ts(ir, named)
    if all_optional?(ir), do: "query?: #{ts};", else: "query: #{ts};"
  end

  defp all_optional?({:remote, mod, name}), do: all_optional?(Type.fetch!(mod, name))
  defp all_optional?({:record, fields}), do: Enum.all?(fields, &(elem(&1, 1) == :optional))
  defp all_optional?(_ir), do: false

  defp path_line(phoenix_path, override, named) do
    names =
      Regex.scan(~r/:([A-Za-z0-9_]+)/, phoenix_path)
      |> Enum.map(fn [_, name] -> String.to_existing_atom(name) end)

    if names == [] do
      "path?: never;"
    else
      "path: #{path_ts(names, override, named)};"
    end
  end

  defp path_ts(names, override, named) do
    override_fields = override_fields(override)
    inner = Enum.map_join(names, "; ", &path_field_ts(&1, override_fields, named))
    "{ #{inner} }"
  end

  defp override_fields({:record, fields}), do: Map.new(fields, fn {n, _r, ir} -> {n, ir} end)
  defp override_fields(nil), do: %{}

  defp path_field_ts(name, override_fields, named) do
    ts =
      case Map.get(override_fields, name) do
        nil -> "string"
        ir -> Emit.ir_to_ts(ir, named)
      end

    "#{name}: #{ts}"
  end

  defp body_ts(nil, _named), do: ""

  defp body_ts(ir, named) do
    "requestBody: { content: { 'application/json': #{Emit.ir_to_ts(ir, named)} } };\n      "
  end

  defp response_ts(204, nil, _named), do: "{ content?: never }"

  defp response_ts(_status, ir, named) do
    "{ content: { 'application/json': #{Emit.ir_to_ts(ir, named)} } }"
  end

  defp indent(text, n) do
    pad = String.duplicate(" ", n)

    text
    |> String.split("\n")
    |> Enum.map_join("\n", &(pad <> &1))
  end
end
